def build_dataset():
    teams_out = []
    team_map = {}
    for t in TEAMS:
        t_obj = {
            "id": t["id"],
            "name": t["name"],
            "normalizedName": normalize(t["name"]),
            "aliases": t["aliases"],
            "country": t["country"],
            "verified": True,
            "primaryColorHex": t["primaryColorHex"],
            "secondaryColorHex": t["secondaryColorHex"],
            "logoUrl": t["logoUrl"],
            "logoAssetPath": None,
            "kitAssetPath": None,
        }
        teams_out.append(t_obj)
        team_map[t["id"]] = t_obj

    players_out = []
    history_out = []
    pair_to_players = {}

    seen_norms = set()
    idx = 1
    for entry in RAW_PLAYERS:
        name, aliases, nat, pos, ovr, mkt_m, age, goals, assists, speed, cl_goals, hist_tuples, extra_clue = entry
        norm = normalize(name)
        if norm in seen_norms:
            continue
        seen_norms.add(norm)

        player_id = f"player_{idx:04d}"
        idx += 1

        # Unique clubs in chronological order
        clubs_ordered = []
        for (tid, s_start, s_end) in hist_tuples:
            if tid not in clubs_ordered:
                clubs_ordered.append(tid)
            hist_id = f"hist_{len(history_out) + 1:04d}"
            history_out.append({
                "id": hist_id,
                "player_id": player_id,
                "team_id": tid,
                "season_start": s_start,
                "season_end": s_end,
                "seasonStart": s_start,
                "seasonEnd": s_end,
                "verified": True,
                "confidence": 1.0,
            })

        club_names = [team_map[tid]["name"] for tid in clubs_ordered if tid in team_map]
        pos_tr = {
            "FW": "Forvet / Hücum",
            "MF": "Orta Saha",
            "DF": "Defans / Savunma",
            "GK": "Kaleci",
        }.get(pos, pos)

        clues = [
            f"Uyruk: {nat} | Mevki: {pos_tr}",
            f"Kariyerinde {goals} gol ve {assists} asist üretti (Overall: {ovr}).",
            f"Oynadığı kulüpler: {', '.join(club_names[:4])}",
            extra_clue,
            f"Baş harfleri: {''.join(w[0].upper() + '.' for w in name.split())} ({len(name.replace(' ', ''))} harfli)",
        ]

        # Build rich aliases (including all words, surname & normalized variants)
        all_aliases = list(aliases)
        parts = name.split()
        for part in parts:
            if len(part) >= 2 and part not in all_aliases:
                all_aliases.append(part)
            norm_part = normalize(part)
            if len(norm_part) >= 2 and norm_part not in [normalize(a) for a in all_aliases]:
                all_aliases.append(norm_part)
        if norm != name.lower() and norm not in [a.lower() for a in all_aliases]:
            all_aliases.append(norm)

        players_out.append({
            "id": player_id,
            "name": name,
            "normalizedName": norm,
            "aliases": all_aliases,
            "nationality": nat,
            "position": pos,
            "verified": True,
            "eaFcOverall": ovr,
            "marketValueEuro": mkt_m * 1_000_000,
            "age": age,
            "goalsCareer": goals,
            "assistsCareer": assists,
            "speedRating": speed,
            "clGoals": cl_goals,
            "clues": clues,
            "photoAssetPath": None,
            "clubs": clubs_ordered,
        })

        # Add to answer_index for every pair of clubs this player played for
        for i in range(len(clubs_ordered)):
            for j in range(i + 1, len(clubs_ordered)):
                pair = sorted([clubs_ordered[i], clubs_ordered[j]])
                key = f"{pair[0]}|{pair[1]}"
                pair_to_players.setdefault(key, [])
                if player_id not in pair_to_players[key]:
                    pair_to_players[key].append(player_id)

    return teams_out, players_out, history_out, pair_to_players

