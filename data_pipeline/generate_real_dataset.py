def normalize(text: str) -> str:
    if not text:
        return ""
    text = text.replace("ı", "i").replace("İ", "i").replace("ß", "ss").replace("ø", "o").replace("Ø", "o")
    nfkd = unicodedata.normalize("NFKD", text)
    ascii_str = "".join(c for c in nfkd if not unicodedata.combining(c))
    clean = "".join(c if c.isalnum() or c.isspace() else " " for c in ascii_str.lower())
    return " ".join(clean.split())

